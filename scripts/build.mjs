import { cp, mkdir, rm, readFile, writeFile } from 'node:fs/promises';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
const root=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const output=resolve(root,'dist');
if(dirname(output)!==root)throw Error('Unexpected output directory.');
await rm(output,{recursive:true,force:true});
await mkdir(output,{recursive:true});
await cp(resolve(root,'frontend/public'),output,{recursive:true});
await cp(resolve(root,'frontend/src'),resolve(output,'src'),{recursive:true});
await cp(resolve(root,'shared'),resolve(output,'shared'),{recursive:true});
await writeFile(resolve(output,'index.html'),await readFile(resolve(root,'frontend/index.html')));
console.log('Built frontend and shared engine into dist/. Backend code and database are excluded.');
